package com.gs1.assessment.api;

import com.fasterxml.jackson.databind.JsonNode;
import com.gs1.assessment.support.TestData;
import org.testng.annotations.DataProvider;
import org.testng.annotations.Test;
import java.time.OffsetDateTime;
import static org.hamcrest.Matchers.equalTo;
import static org.hamcrest.Matchers.not;
import static org.hamcrest.Matchers.blankOrNullString;
import static org.testng.Assert.assertNotNull;

public final class GetBookTest extends BooksTestBase {
    @DataProvider(name = "existingBooks")
    public Object[][] existingBooks() {
        JsonNode data = TestData.read("data/book-cases.json").required("existingBook");
        return new Object[][] {{data.required("id").asInt(), data.required("title").asText(),
                data.required("pageCount").asInt()}};
    }

    @Test(groups = "api", dataProvider = "existingBooks", description = "Happy path: retrieve an existing book")
    public void retrievesExistingBook(int id, String title, int pageCount) {
        Book actual = books.getBook(id).statusCode(200).contentType("application/json")
                .body("id", equalTo(id)).body("title", equalTo(title)).body("pageCount", equalTo(pageCount))
                .body("description", not(blankOrNullString())).body("excerpt", not(blankOrNullString()))
                .extract().as(Book.class);
        assertNotNull(actual.publishDate(), "Publish date must be provided");
        // Dates are generated by this fake service; validate the format instead of a changing literal.
        OffsetDateTime.parse(actual.publishDate());
    }
}
